// Shared plumbing for the DSH live-integration harness.
//
// Everything in this module was derived from live probes of `dsh` 0.2.1-rc.3 on
// 2026-10-26 (captures preserved in test/fixtures/real/). Two findings shape the
// whole file and are easy to regress:
//
//   1. Launcher flags must come BEFORE app flags. `dsh` parses its own launcher
//      options (`--profile`, `--patch`, `--dump-config`) only up to the first
//      argument it does not recognise. Put `--json` first and `--patch` is handed
//      to the headless app, which answers
//      `{"type":"error","message":"unknown option '--patch'"}` and exits 1.
//      `launcherArgs()` exists so no caller has to remember that ordering.
//
//   2. A SIGTERM'd turn exits with code 0 and an empty `final`, and emits no
//      `turn_end`. Exit code alone therefore does not mean "turn completed".

import { spawn, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

export const DEFAULT_PROFILE = "headless";

// Plugins the harness disables so a headless `--json` turn is reproducible: they
// inject extra prompt text, gate tool calls, or add their own tools. None of them
// is a transport concern, so the contract checks stay about `dsh` itself.
//
// `tokenomics` used to be load-bearing here (it threw `RangeError: Invalid string
// length` inside its stream handler and took the boot down before the model was
// called); it was removed from the profiles on 2026-10-26, so it is no longer
// listed.
export const DISABLED_PLUGINS = [
  "dsh-onepassword-tools",
  "dsh-pr-claim-gate",
  "ponytail",
  "guardrails",
];

export const KNOWN_EVENT_TYPES = new Set([
  "session",
  "status",
  "thinking",
  "text",
  "tool_call",
  "tool_result",
  "final",
  "error",
]);

export function resolveBinary(env = process.env) {
  return env.DSH_BIN || "dsh";
}

/** Probe the binary. Never throws: a missing `dsh` is a normal, reportable state. */
export function probeBinary(bin = resolveBinary()) {
  const result = spawnSync(bin, ["--version"], {
    encoding: "utf8",
    timeout: 20_000,
    env: process.env,
  });
  if (result.error) {
    return {
      available: false,
      bin,
      reason:
        result.error.code === "ENOENT"
          ? `\`${bin}\` not found on PATH (set DSH_BIN to override)`
          : `\`${bin} --version\` failed: ${result.error.message}`,
    };
  }
  if (result.status !== 0) {
    return {
      available: false,
      bin,
      reason: `\`${bin} --version\` exited ${result.status}: ${(result.stderr || "").trim().slice(0, 400)}`,
    };
  }
  const version = (result.stdout || "").trim().split("\n")[0].trim();
  return { available: true, bin, version };
}

/** Write the minimal-overlay YAML that keeps a headless turn reproducible. */
export function writeOverlay(dir, { modelOverride = null } = {}) {
  const lines = ["# Generated by the dsh-provider test harness. Do not edit in place."];
  for (const id of DISABLED_PLUGINS) {
    lines.push(`- id: ${id}`, "  disabled: true");
  }
  if (modelOverride) {
    lines.push(
      "- id: agent-default-model",
      '  name: "@deepseek-ai/dsh-agent-default-model"',
      "  config:",
      `    provider: ${modelOverride.provider}`,
      `    model: ${modelOverride.model}`,
    );
  }
  const path = join(dir, modelOverride ? "overlay.model.yml" : "overlay.yml");
  const text = `${lines.join("\n")}\n`;
  writeFileSync(path, text, "utf8");
  return { path, text, sha256: createHash("sha256").update(text).digest("hex") };
}

export function makeScratchDir(prefix = "dsh-harness-") {
  return mkdtempSync(join(tmpdir(), prefix));
}

export function removeDir(dir) {
  rmSync(dir, { recursive: true, force: true });
}

/**
 * Compose argv with launcher flags strictly before app flags.
 * `appArgs` is the headless app's own argv: `--json`, `--session-id <id>`, then
 * the task text as the final element.
 */
export function launcherArgs({ profile = DEFAULT_PROFILE, overlays = [], appArgs = [] }) {
  const args = ["--profile", profile];
  for (const overlay of overlays) args.push("--patch", overlay);
  args.push(...appArgs);
  return args;
}

export function parseNdjson(text) {
  const events = [];
  const malformed = [];
  const lines = text.split("\n");
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index].trim();
    if (!line) continue;
    try {
      const value = JSON.parse(line);
      if (!value || typeof value !== "object" || Array.isArray(value)) {
        malformed.push({ line: index + 1, text: line, reason: "not a JSON object" });
        continue;
      }
      events.push(value);
    } catch (error) {
      malformed.push({ line: index + 1, text: line, reason: error.message });
    }
  }
  return { events, malformed };
}

/**
 * Run one `dsh` invocation. Resolves — it never rejects on a non-zero exit, because
 * a failing turn is data the harness must inspect.
 */
export function runDsh({
  bin = resolveBinary(),
  args,
  cwd,
  timeoutMs = 180_000,
  interruptAfterMs = null,
  env = {},
}) {
  return new Promise((resolve, reject) => {
    const startedAt = Date.now();
    const detached = process.platform !== "win32";
    const child = spawn(bin, args, {
      cwd,
      env: { ...process.env, ...env },
      stdio: ["ignore", "pipe", "pipe"],
      detached,
    });

    const stdoutChunks = [];
    const stderrChunks = [];
    let interrupted = false;
    let timedOut = false;
    let settled = false;
    let killTimer = null;

    child.stdout.on("data", (chunk) => stdoutChunks.push(chunk));
    child.stderr.on("data", (chunk) => stderrChunks.push(chunk));

    const signalTree = (signal) => {
      try {
        child.kill(signal);
      } catch {
        // Already gone.
      }
      if (!detached) return;
      try {
        process.kill(-child.pid, signal);
      } catch {
        // Group already reaped.
      }
    };

    const interruptTimer = interruptAfterMs
      ? setTimeout(() => {
          interrupted = true;
          signalTree("SIGTERM");
        }, interruptAfterMs)
      : null;

    const timeoutTimer = setTimeout(() => {
      timedOut = true;
      signalTree("SIGTERM");
      killTimer = setTimeout(() => signalTree("SIGKILL"), 5_000);
    }, timeoutMs);

    const finish = (exitCode, signal) => {
      if (settled) return;
      settled = true;
      clearTimeout(interruptTimer);
      clearTimeout(timeoutTimer);
      clearTimeout(killTimer);
      if (detached) {
        try {
          process.kill(-child.pid, "SIGTERM");
        } catch {
          // Group already gone; the common case.
        }
      }
      const stdout = Buffer.concat(stdoutChunks).toString("utf8");
      const stderr = Buffer.concat(stderrChunks).toString("utf8");
      const { events, malformed } = parseNdjson(stdout);
      resolve({
        argv: [bin, ...args],
        cwd,
        events,
        malformed,
        stdout,
        stderr,
        exitCode,
        signal,
        interrupted,
        timedOut,
        durationMs: Date.now() - startedAt,
      });
    };

    child.on("error", (error) => {
      if (settled) return;
      settled = true;
      clearTimeout(interruptTimer);
      clearTimeout(timeoutTimer);
      reject(error);
    });
    child.on("close", finish);
  });
}

const firstLine = (text) =>
  (text || "")
    .split("\n")
    .map((l) => l.trim())
    .find(Boolean) || "";

/**
 * Contract invariants for one invocation's event stream.
 *
 * `expect` is one of:
 *   "completed" — the turn finished: one `turn_end` with `reason.kind === "completed"`,
 *                 non-empty `final.text`
 *   "error"     — the turn failed: one `turn_end` with `reason.kind === "error"`, exit 1
 *   "interrupt" — SIGTERM mid-turn: `final` present with empty text, NO `turn_end`
 *
 * Returns { failures, warnings } — both arrays of strings.
 */
// oxlint-disable-next-line complexity -- one flat list of independent contract assertions; each line is a check.
export function checkContract(run, { expect = "completed", label = "turn" } = {}) {
  const failures = [];
  const warnings = [];
  const { events, malformed } = run;
  const fail = (message) => failures.push(`${label}: ${message}`);

  for (const bad of malformed) {
    fail(`stdout line ${bad.line} is not valid JSON (${bad.reason}): ${bad.text.slice(0, 160)}`);
  }
  if (events.length === 0) {
    fail("emitted no events on stdout");
    return { failures, warnings };
  }

  const first = events[0];
  if (first.type !== "session") {
    fail(`first event must be \`session\`, got \`${first.type}\``);
  } else if (typeof first.sessionId !== "string" || !first.sessionId.trim()) {
    fail("`session` event has no sessionId");
  } else if (!/^session-[0-9a-zA-Z-]+$/.test(first.sessionId)) {
    warnings.push(`${label}: unexpected sessionId shape \`${first.sessionId}\``);
  }

  const sessionEvents = events.filter((event) => event.type === "session");
  if (sessionEvents.length > 1) {
    fail(`emitted ${sessionEvents.length} \`session\` events in one invocation (expected 1)`);
  }

  const finalIndex = events.findIndex((event) => event.type === "final");
  const isInterrupt = expect === "interrupt";
  // A SIGTERM'd turn emits `final` only when the signal lands between steps. When it
  // lands inside a tool call the stream simply stops — verified 2026-10-26: the last
  // line was a `tool_call` and no `final` ever arrived. The provider must therefore
  // treat the child's exit as the authoritative end of an interrupted turn, never
  // `final`.
  if (finalIndex === -1) {
    if (!isInterrupt) fail("no `final` event");
  } else {
    if (finalIndex !== events.length - 1) {
      fail(
        `\`final\` at index ${finalIndex} is followed by ${events.length - 1 - finalIndex} event(s)`,
      );
    }
    if (typeof events[finalIndex].text !== "string") {
      fail("`final` event has no string `text`");
    }
  }
  if (events.filter((event) => event.type === "final").length > 1) {
    fail("emitted more than one `final` event");
  }

  const turnEnds = events.filter((event) => event.type === "status" && event.phase === "turn_end");
  const turnStarts = events.filter(
    (event) => event.type === "status" && event.phase === "turn_start",
  );
  if (turnStarts.length === 0) fail("no `turn_start` status event");

  const finalText = finalIndex >= 0 ? events[finalIndex].text : undefined;

  if (expect === "interrupt") {
    if (turnEnds.length > 0) {
      fail(`interrupted turn emitted ${turnEnds.length} \`turn_end\` event(s); expected none`);
    }
    if (typeof finalText === "string" && finalText.trim() !== "") {
      warnings.push(
        `${label}: interrupted turn carried non-empty final text (${finalText.length} chars)`,
      );
    }
    return { failures, warnings };
  }

  if (turnEnds.length === 0) {
    fail("no `turn_end` status event");
    return { failures, warnings };
  }
  if (turnEnds.length > 1) {
    fail(`emitted ${turnEnds.length} \`turn_end\` events in one invocation (expected 1)`);
  }
  const reason = turnEnds[turnEnds.length - 1].reason;
  if (!reason || typeof reason !== "object" || typeof reason.kind !== "string") {
    fail("`turn_end` has no `reason.kind`");
  } else if (reason.kind !== expect) {
    fail(`\`turn_end\` reason.kind is \`${reason.kind}\`, expected \`${expect}\``);
  }

  if (expect === "completed") {
    if (typeof finalText === "string" && finalText.trim() === "") {
      fail("completed turn has empty `final.text`");
    }
    if (run.exitCode !== 0) {
      fail(`completed turn exited ${run.exitCode} (expected 0)`);
    }
  }
  if (expect === "error") {
    if (run.exitCode === 0) fail("error turn exited 0 (expected non-zero)");
    if (reason && reason.kind === "error" && (!reason.error || !reason.error.message)) {
      warnings.push(`${label}: \`turn_end\` error reason carries no message`);
    }
  }

  // Tool call/result pairing — a provider that loses callIds cannot render tools.
  const openCalls = new Map();
  for (const event of events) {
    if (event.type === "tool_call") {
      if (typeof event.callId !== "string" || !event.callId) {
        fail("`tool_call` without callId");
      } else {
        openCalls.set(event.callId, event.tool);
      }
      if (typeof event.tool !== "string" || !event.tool) {
        warnings.push(`${label}: \`tool_call\` ${event.callId} has no tool name`);
      }
    }
    if (event.type === "tool_result" && typeof event.callId === "string") {
      if (!openCalls.has(event.callId)) {
        warnings.push(`${label}: \`tool_result\` for unknown callId \`${event.callId}\``);
      } else {
        openCalls.delete(event.callId);
      }
    }
  }
  for (const callId of openCalls.keys()) {
    warnings.push(`${label}: \`tool_call\` ${callId} never received a \`tool_result\``);
  }

  for (const event of events) {
    if (!KNOWN_EVENT_TYPES.has(event.type)) {
      warnings.push(`${label}: unknown event type \`${event.type}\``);
    }
  }

  // Usage blocks appear on `step_end` only when the model actually ran.
  for (const event of events) {
    if (event.type !== "status" || event.phase !== "step_end") continue;
    if (!event.usage) continue;
    for (const key of ["inputTokens", "outputTokens", "totalTokens"]) {
      if (typeof event.usage[key] !== "number") {
        warnings.push(`${label}: \`step_end\` usage.${key} is not a number`);
      }
    }
  }

  return { failures, warnings };
}

/** First meaningful line of stderr, for provenance and failure reports. */
export function stderrSummary(stderr) {
  return firstLine(stderr);
}
